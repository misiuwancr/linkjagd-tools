def validate(entries: list[dict]) -> None:
    errors: list[str] = []
    names: set[str] = set()
    domains: dict[str, str] = {}
    shared = {"github.com", "gitlab.com", "invent.kde.org", "huggingface.co", "apps.apple.com", "chromewebstore.google.com"}
    for entry in entries:
        if entry["name"] in names:
            errors.append(f"doppelter Name {entry['name']}")
        names.add(entry["name"])
        key = entry["domain"]
        path = entry["originalUrl"]
        if key in domains and key not in shared:
            errors.append(f"doppelte Domain {key}: {entry['name']} und {domains[key]}")
        domains[key] = entry["name"]
        short = entry["shortDescriptionDe"]
        if not (10 <= len(short) <= 280):
            errors.append(f"Kurztextlänge {entry['name']}: {len(short)}")
        if "zzgl" in entry["longDescriptionDe"].lower() or "zzgl" in short.lower():
            errors.append(f"USt-Formulierung {entry['name']}")
        if entry["partnerStatus"] != "none_found":
            errors.append(f"Partnerstatus {entry['name']}")
        for use in entry["useCasesDe"]:
            if len(use) > 180:
                errors.append(f"Use-Case zu lang {entry['name']}: {len(use)}")
        for feature in entry["featuresDe"]:
            if len(feature) > 180:
                errors.append(f"Feature zu lang {entry['name']}: {len(feature)}")
        if entry["licenseType"] == "open_source":
            block = entry["oss"]
            if not block or not block.get("license") or not block.get("repoUrl"):
                errors.append(f"OSS unvollständig {entry['name']}")
        if entry["licenseType"] != "open_source" and entry["oss"] is not None:
            errors.append(f"OSS-Block trotz {entry['licenseType']} {entry['name']}")
        if not path.startswith("https://"):
            errors.append(f"keine https-URL {entry['name']}")
    if errors:
        raise SystemExit("\n".join(errors))


